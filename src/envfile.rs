use std::collections::HashMap;
use std::fs::{self, File};
use std::io::{BufRead, BufReader, Write};
use std::path::Path;

pub const DEFAULT_WEB_ENV_FILE: &str = "/root/conf/web.env";

pub fn get_web_env_file() -> String {
    get_env_default("WEB_ENV_FILE", DEFAULT_WEB_ENV_FILE)
}

pub fn get_env_default(key: &str, default_val: &str) -> String {
    match std::env::var(key) {
        Ok(val) if !val.trim().is_empty() => val,
        _ => default_val.to_string(),
    }
}

pub fn get_env_bool(key: &str, default_val: bool) -> bool {
    match std::env::var(key) {
        Ok(val) => {
            let trimmed = val.trim().to_lowercase();
            if trimmed.is_empty() {
                default_val
            } else {
                trimmed == "true" || trimmed == "1"
            }
        }
        Err(_) => default_val,
    }
}

pub fn get_env_int(key: &str, default_val: i32) -> i32 {
    match std::env::var(key) {
        Ok(val) => {
            let trimmed = val.trim();
            if trimmed.is_empty() {
                default_val
            } else {
                match trimmed.parse::<i32>() {
                    Ok(n) => n,
                    Err(_) => {
                        eprintln!(
                            "警告: {}={:?} 不是合法整数，使用默认值: {}",
                            key, val, default_val
                        );
                        default_val
                    }
                }
            }
        }
        Err(_) => default_val,
    }
}

pub fn parse_port(s: &str) -> anyhow::Result<u16> {
    let port = s
        .trim()
        .parse::<u16>()
        .map_err(|e| anyhow::anyhow!("端口格式错误: {}", e))?;
    if port == 0 {
        return Err(anyhow::anyhow!("端口范围必须在 1-65535，当前: 0"));
    }
    Ok(port)
}

pub fn load_persisted_env() -> anyhow::Result<()> {
    let env_file = get_web_env_file();
    let values = read_env_file(&env_file)?;

    for (key, value) in values {
        let is_empty = std::env::var(&key).map(|v| v.trim().is_empty()).unwrap_or(true);
        if is_empty {
            std::env::set_var(&key, &value);
        }
    }
    Ok(())
}

pub fn read_env_file(path: &str) -> anyhow::Result<HashMap<String, String>> {
    let mut values = HashMap::new();
    let p = Path::new(path);
    if !p.exists() {
        return Ok(values);
    }

    let file = File::open(p)?;
    let reader = BufReader::new(file);

    for line_result in reader.lines() {
        let line = line_result?;
        let trimmed = line.trim();
        if trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }

        if let Some((k, v)) = trimmed.split_once('=') {
            let key = k.trim().to_string();
            if key.is_empty() {
                continue;
            }
            let mut val = v.trim().to_string();
            if (val.starts_with('"') && val.ends_with('"'))
                || (val.starts_with('\'') && val.ends_with('\''))
            {
                if val.len() >= 2 {
                    if let Ok(unquoted) = serde_json::from_str::<String>(&val) {
                        val = unquoted;
                    } else {
                        val = val[1..val.len() - 1].to_string();
                    }
                }
            }
            values.insert(key, val);
        }
    }

    Ok(values)
}

pub fn write_env_file(path: &str, values: &HashMap<String, String>) -> anyhow::Result<()> {
    let p = Path::new(path);
    if let Some(parent) = p.parent() {
        fs::create_dir_all(parent)?;
    }

    let mut keys: Vec<&String> = values
        .keys()
        .filter(|k| !k.trim().is_empty() && !values[*k].trim().is_empty())
        .collect();
    keys.sort();

    let mut content = String::from("# Generated by mymihomo web config\n");
    for k in keys {
        let val = &values[k];
        let quoted = serde_json::to_string(val).unwrap_or_else(|_| format!("\"{}\"", val));
        content.push_str(&format!("{}={}\n", k, quoted));
    }

    let mut file = File::create(p)?;
    file.write_all(content.as_bytes())?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_read_write_env() {
        let tmp_dir = std::env::temp_dir();
        let file_path = tmp_dir.join("test_mymihomo.env");
        let path_str = file_path.to_str().unwrap();

        let mut map = HashMap::new();
        map.insert("CONF_URL".to_string(), "https://example.com/sub".to_string());
        map.insert("MIXED_PORT".to_string(), "7890".to_string());

        write_env_file(path_str, &map).unwrap();

        let loaded = read_env_file(path_str).unwrap();
        assert_eq!(loaded.get("CONF_URL"), Some(&"https://example.com/sub".to_string()));
        assert_eq!(loaded.get("MIXED_PORT"), Some(&"7890".to_string()));

        let _ = fs::remove_file(file_path);
    }
}
